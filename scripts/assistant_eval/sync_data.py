#!/usr/bin/env python3
"""Embed the assistant eval's catalogue and DEMO bundle in the tests (AttndTests/AssistantEvalData.swift).

The canonical files live in attnd-web: docs/assistant_eval/questions.json and demo_bundle.json (made by
`manage.py export_assistant_eval_bundle`). Run this after either changes:

    python3 scripts/assistant_eval/sync_data.py                      # attnd-web next to this repo (../Attnd-Web)
    python3 scripts/assistant_eval/sync_data.py --web /path/to/Attnd-Web

Embedding (rather than test resources) lets the same tests run on the simulator, a device and the Linux harness.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def literal(text):
    hashes = '#'
    while f'"""{hashes}' in text:
        hashes += '#'
    return f'{hashes}"""\n{text}\n"""{hashes}'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--web', default=str(ROOT.parent / 'Attnd-Web'))
    args = parser.parse_args()
    folder = Path(args.web) / 'docs' / 'assistant_eval'
    questions = json.loads((folder / 'questions.json').read_text())
    bundle = json.loads((folder / 'demo_bundle.json').read_text())
    q_text = json.dumps(questions, ensure_ascii=False, separators=(',', ':'))
    b_text = json.dumps(bundle, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    out = ROOT / 'AttndTests' / 'AssistantEvalData.swift'
    out.write_text(
        '// AssistantEvalData.swift\n// AttndTests\n//\n'
        '// GENERATED by scripts/assistant_eval/sync_data.py from attnd-web docs/assistant_eval/\n'
        f'// (questions.json v{questions["version"]}: {len(questions["questions"])} questions; demo_bundle.json). Do not edit.\n\n'
        'enum AssistantEvalData {\n'
        f'    static let questionsJSON = {literal(q_text)}\n\n'
        f'    static let bundleJSON = {literal(b_text)}\n'
        '}\n')
    print(f'Wrote {out.relative_to(ROOT)}: {len(questions["questions"])} questions.')


if __name__ == '__main__':
    main()
