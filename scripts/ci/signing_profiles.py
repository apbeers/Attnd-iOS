#!/usr/bin/env python3
"""Manual App Store signing for CI (macOS runner).

Reads the three App Store provisioning profiles (base64 in IOS_PROFILE_APP_B64, IOS_PROFILE_WIDGETS_B64,
IOS_PROFILE_CLIP_B64), installs them where Xcode looks, checks that every entitlement each target asks for
is in its profile (so a capability missing on the App ID fails here with a clear message instead of deep in
xcodebuild), and writes:
  build/Signing.xcconfig        -xcconfig for the archive: Apple Distribution + the profile per target
  build/export-profiles.plist   the ExportOptions `provisioningProfiles` dict (bundle id -> profile UUID)

Usage: signing_profiles.py <out dir>
"""
import base64, os, plistlib, subprocess, sys, datetime, pathlib

TEAM = os.environ.get("APPLE_TEAM_ID", "GQQX4L6TE2")
# target name -> (bundle id, entitlements file, secret holding its profile)
TARGETS = {
    "Attnd": ("com.arcu.Attnd", "Attnd/Attnd.entitlements", "IOS_PROFILE_APP_B64"),
    "AttndAppClip": ("com.arcu.Attnd.clip", "AttndAppClip/AttndAppClip.entitlements", "IOS_PROFILE_CLIP_B64"),
    "AttndWidgets": ("com.arcu.Attnd.widgets", "AttndWidgets/AttndWidgets.entitlements", "IOS_PROFILE_WIDGETS_B64"),
}
# Keys Xcode or the profile handle itself; never in a capability check.
IGNORED = {"application-identifier", "com.apple.developer.team-identifier", "keychain-access-groups",
           "get-task-allow", "beta-reports-active"}
# Capability names for the error message.
NAMES = {
    "com.apple.security.application-groups": "App Groups",
    "com.apple.developer.weatherkit": "WeatherKit",
    "aps-environment": "Push Notifications",
    "com.apple.developer.associated-domains": "Associated Domains",
    "com.apple.developer.usernotifications.time-sensitive": "Time Sensitive Notifications",
    "com.apple.developer.devicecheck.appattest-environment": "App Attest",
    "com.apple.developer.parent-application-identifiers": "App Clip (parent application)",
}


def decode_profile(data: bytes) -> dict:
    raw = subprocess.run(["security", "cms", "-D"], input=data, capture_output=True, check=True).stdout
    return plistlib.loads(raw)


def main() -> int:
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "build")
    out.mkdir(parents=True, exist_ok=True)
    dirs = [pathlib.Path.home() / "Library/MobileDevice/Provisioning Profiles",
            pathlib.Path.home() / "Library/Developer/Xcode/UserData/Provisioning Profiles"]
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)

    lines = ["// Generated by scripts/ci/signing_profiles.py (CI only).",
             "CODE_SIGN_STYLE = Manual", "CODE_SIGN_IDENTITY = Apple Distribution", f"DEVELOPMENT_TEAM = {TEAM}",
             "PROVISIONING_PROFILE_SPECIFIER = $(ATTND_PROFILE_$(TARGET_NAME))"]
    export = {}
    problems = []
    now = datetime.datetime.now(datetime.timezone.utc)
    for target, (bundle_id, ent_file, secret) in TARGETS.items():
        b64 = os.environ.get(secret, "").strip()
        if not b64:
            problems.append(f"{secret} is not set (the App Store profile for {bundle_id})")
            continue
        data = base64.b64decode(b64)
        profile = decode_profile(data)
        uuid, name = profile["UUID"], profile.get("Name", "?")
        ents = profile.get("Entitlements", {})
        app_id = ents.get("application-identifier", "")
        expires = profile.get("ExpirationDate")
        if expires is not None and expires.tzinfo is None:
            expires = expires.replace(tzinfo=datetime.timezone.utc)
        print(f"{target}: profile '{name}' {uuid} for {app_id}, expires {expires:%Y-%m-%d}" if expires else
              f"{target}: profile '{name}' {uuid} for {app_id}")
        print("  entitlements: " + ", ".join(sorted(k for k in ents if k not in IGNORED)))
        if app_id != f"{TEAM}.{bundle_id}":
            problems.append(f"{secret} is a profile for {app_id}, expected {TEAM}.{bundle_id}")
        if ents.get("get-task-allow"):
            problems.append(f"{secret} ('{name}') is a development profile; use an App Store profile")
        if expires and expires < now:
            problems.append(f"{secret} ('{name}') expired on {expires:%Y-%m-%d}")
        elif expires and (expires - now).days < 30:
            print(f"::warning title=Signing::Profile '{name}' expires on {expires:%Y-%m-%d}; renew it (SETUP.md)")
        wanted = plistlib.loads(pathlib.Path(ent_file).read_bytes())
        for key in wanted:
            if key not in IGNORED and key not in ents:
                problems.append(f"{target} needs {NAMES.get(key, key)} ({key}), but profile '{name}' doesn't "
                                f"have it: enable it on the App ID {bundle_id}, then regenerate the profile "
                                f"and update {secret}")
        for d in dirs:
            (d / f"{uuid}.mobileprovision").write_bytes(data)
        lines.append(f"ATTND_PROFILE_{target} = {uuid}")
        export[bundle_id] = uuid

    for p in problems:
        print(f"::error title=Signing::{p}")
    if problems:
        return 1
    (out / "Signing.xcconfig").write_text("\n".join(lines) + "\n")
    (out / "export-profiles.plist").write_bytes(plistlib.dumps(export))
    return 0


if __name__ == "__main__":
    sys.exit(main())
